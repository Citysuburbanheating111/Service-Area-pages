/**
 * Builds apps-script/ServiceAreaPages.gs, the file pasted into the City Suburban writing sheet's Apps Script project.
 *
 *   npm run apps-script:build
 *
 * The columns come from the referenceServicePage Sanity schema, so the sheet and Sanity can't drift. Rebuild (and
 * re-paste) after a schema change; `npm run test:apps-script` fails while the committed file is out of date.
 */
import fs from 'node:fs'
import path from 'node:path'
import {build} from 'esbuild'
import {areaPage} from '../src/sanity/schemaTypes/areaPage'
import {itemTypes, sheetColumns, type SchemaField} from './lib/sheet'
import {AREA_SHEET_OPTIONS} from './lib/area-sheet-rules'

export const OUT_FILE = path.resolve('apps-script/ServiceAreaPages.gs')
const PREFIX = 'serviceAreaPages'

export async function buildAppsScript(): Promise<string> {
  const fields = (areaPage as unknown as {fields: SchemaField[]}).fields
  const columns = sheetColumns(fields, AREA_SHEET_OPTIONS)
  const config = JSON.parse(fs.readFileSync(path.resolve('apps-script/config.json'), 'utf8'))
  const result = await build({
    entryPoints: [path.resolve('apps-script/src/service-area-pages.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: 'ServiceAreaPagesLib',
    target: 'es2020',
    platform: 'neutral',
    charset: 'utf8',
    legalComments: 'none',
    define: {__COLUMNS__: JSON.stringify(columns), __TYPES__: JSON.stringify(itemTypes(fields)), __CONFIG__: JSON.stringify(config)},
  })
  const header = [
    `// Service area pages -> Sanity (tab "${config.tab}" only).`,
    '// GENERATED by `npm run apps-script:build` in Citysuburbanheating111/Service-Area-pages (web/).',
    '// Do not edit here: change apps-script/src/ or the Sanity schema, rebuild, re-paste.',
    `// ${columns.length} field columns from the areaPage schema; Sanity project ${config.projectId}, dataset ${config.dataset}.`,
    '',
  ].join('\n')
  const entryPoints = [
    '',
    '// Menu actions (global names, so they never clash with the other tab\'s script in this spreadsheet).',
    ...['Menu:menu', 'Check:check', 'Push:push', 'SetToken:setToken', 'Load:load', 'Add:add', 'Get:get'].map((pair) => {
      const [name, method] = pair.split(':')
      return `function ${PREFIX}${name}() { ServiceAreaPagesLib.sheet.${method}() }`
    }),
    '// Called from the Add box in the browser (google.script.run), so it returns the report.',
    `function ${PREFIX}AddFromClaude(text, write) { return ServiceAreaPagesLib.sheet.addFromClaude(text, write) }`,
    '',
  ].join('\n')
  return header + result.outputFiles[0].text + entryPoints
}

if (process.argv[1] && path.resolve(process.argv[1]).replace(/\.ts$/, '') === path.resolve('scripts/build-apps-script').replace(/\.ts$/, '')) {
  buildAppsScript().then((code) => {
    fs.writeFileSync(OUT_FILE, code)
    console.log(`Wrote ${path.relative(process.cwd(), OUT_FILE)} (${Math.round(code.length / 1024)} KB). Paste it into the sheet's Apps Script project as ServiceAreaPages.gs.`)
  }).catch((error: unknown) => { console.error(error); process.exit(1) })
}
